def split_sections(text: str, level: str) -> list[tuple[str, str]]:
    """Split markdown into (heading, body) pairs at the given heading level."""
    pattern = re.compile(rf"^{re.escape(level)} (.+)$", re.M)
    matches = list(pattern.finditer(text))
    sections = []
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections.append((m.group(1).strip(), text[m.end():end].strip("\n")))
    return sections


def generate_cli(tritonctl: str) -> tuple[str, list[tuple[str, str]]]:
    version = subprocess.run(
        [tritonctl, "--version"], check=True, capture_output=True, text=True
    ).stdout.strip()
    full = subprocess.run(
        [tritonctl, "llms-full.txt"], check=True, capture_output=True, text=True
    ).stdout

    guide, sep, reference = full.partition("\n## Command reference\n")
    if not sep:
        sys.exit("llms-full.txt has no '## Command reference' section")

    source = f"`{version} llms-full.txt`"
    write("cli/guide.md", banner(source) + "\n" + guide.strip())

    sections = split_sections(reference, "###")
    groups = {
        name for name, body in sections
        if name.startswith("tritonctl ") and re.search(r"^Subcommands:", body, re.M)
    }
    counts: dict[str, int] = {}
    for name, _ in sections:
        words = name.split()
        if len(words) >= 2:
            counts[words[1]] = counts.get(words[1], 0) + 1

    files: "OrderedDict[str, list[tuple[str, str]]]" = OrderedDict()
    for name, body in sections:
        words = name.split()
        if words[0] != "tritonctl":
            key = "global-flags"
        elif len(words) == 1 or f"tritonctl {words[1]}" not in groups:
            key = "core"
        elif (
            counts[words[1]] > SPLIT_THRESHOLD
            and len(words) >= 3
            and f"tritonctl {words[1]} {words[2]}" in groups
        ):
            key = f"{words[1]}-{words[2]}"
        else:
            key = words[1]
        files.setdefault(key, []).append((name, body))

    index = []
    for key, items in files.items():
        title = {
            "global-flags": "Global flags",
            "core": "Session, shortcuts and help",
        }.get(key, items[0][0])
        parts = [banner(source), f"# {title}\n"]
        for name, body in items:
            parts.append(f"{body}\n" if name == title else f"## {name}\n\n{body}\n")
        write(f"cli/{key}.md", "\n".join(parts))
        first = items[0][1].split("\n\n")[0].replace("\n", " ").strip()
        index.append((key, first if key not in ("global-flags", "core") else title))

    lines = [banner(source), "# tritonctl command reference\n",
             f"Built from `{version}`. Start with [guide.md](guide.md).\n",
             "| File | Covers |", "|---|---|"]
    for key, about in index:
        lines.append(f"| [{key}.md]({key}.md) | {about} |")
    write("cli/README.md", "\n".join(lines))
    return version, index


