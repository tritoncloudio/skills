#!/usr/bin/env python3
"""Regenerate skills/tritoncloud/references from tritonctl and mariana-trench.

Usage: generate.py --tritonctl <binary> --source <mariana-trench checkout>
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "skills" / "tritoncloud" / "references"

SPEC = "openapi-specs/generated/triton-cloud-api/triton-cloud-api-latest.json"

# (source path in mariana-trench, output path under references/)
COPIED_DOCS = [
    ("sdks/python/README.md", "sdk/python.md"),
    ("sdks/typescript/README.md", "sdk/typescript.md"),
    ("sdks/mcp/README.md", "sdk/mcp.md"),
    ("docs/sandboxes/quickstart.md", "guides/sandboxes-quickstart.md"),
    ("docs/sandbox-github.md", "guides/sandbox-github.md"),
]

# Relative links in copied docs that point elsewhere in mariana-trench.
LINK_REWRITES = {
    "../sandbox-github.md": "sandbox-github.md",
}

# Parameters that only an operator can set; tenants never send them.
OPERATOR_PARAMS = {"silo"}

# A command group with more sections than this gets one file per subgroup.
SPLIT_THRESHOLD = 15


def banner(source: str) -> str:
    return f"<!-- Generated by scripts/generate.py from {source}. Do not edit. -->\n"


def write(rel: str, text: str) -> None:
    path = OUT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n")


def git_rev(source: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(source), "rev-parse", "--short=12", "HEAD"],
            check=True, capture_output=True, text=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


