def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def schema_type(schema: dict) -> str:
    if not schema:
        return "any"
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        return f"[{name}](schemas.md#{name.lower()})"
    for key in ("allOf", "oneOf", "anyOf"):
        if key in schema:
            inner = " \\| ".join(schema_type(s) for s in schema[key])
            return inner
    t = schema.get("type", "object")
    if t == "array":
        return f"array of {schema_type(schema.get('items', {}))}"
    if t == "object" and "additionalProperties" in schema and isinstance(schema["additionalProperties"], dict):
        return f"map of {schema_type(schema['additionalProperties'])}"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    fmt = schema.get("format")
    return f"{t} ({fmt})" if fmt else t


def cell(text) -> str:
    return re.sub(r"\s+", " ", str(text or "")).replace("|", "\\|").strip()


def body_schema(content: dict) -> str:
    if not content:
        return ""
    out = []
    for mime, media in content.items():
        s = media.get("schema")
        out.append(f"`{mime}`" + (f": {schema_type(s)}" if s else ""))
    return "; ".join(out)


def generate_api(source: Path) -> list[tuple[str, str, int]]:
    spec = json.loads((source / SPEC).read_text())
    info = spec["info"]
    src = f"`{SPEC}` (version {info['version']})"
    tag_desc = {t["name"]: t.get("description", "") for t in spec.get("tags", [])}
    schemas = spec.get("components", {}).get("schemas", {})

    by_tag: "OrderedDict[str, list]" = OrderedDict()
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            for tag in op.get("tags", ["untagged"]):
                by_tag.setdefault(tag, []).append((path, method.upper(), op))

    index = []
    for tag in sorted(by_tag):
        ops = by_tag[tag]
        parts = [banner(src), f"# {tag}\n", tag_desc.get(tag, "") + "\n"]
        for path, method, op in ops:
            text = " ".join(x for x in (op.get("summary"), op.get("description")) if x)
            parts.append(f"## {method} {path}\n")
            parts.append(f"Operation `{op.get('operationId', '')}`.\n")
            if text:
                parts.append(text.strip() + "\n")
            params = [p for p in op.get("parameters", []) if p.get("name") not in OPERATOR_PARAMS]
            if params:
                parts.append("| Parameter | In | Required | Type | Description |")
                parts.append("|---|---|---|---|---|")
                for p in params:
                    parts.append(
                        f"| `{p['name']}` | {p['in']} | {'yes' if p.get('required') else 'no'} "
                        f"| {schema_type(p.get('schema', {}))} | {cell(p.get('description'))} |"
                    )
                parts.append("")
            rb = op.get("requestBody")
            if rb:
                parts.append(f"Request body{' (required)' if rb.get('required') else ''}: "
                             f"{body_schema(rb.get('content', {}))}\n")
            rows = []
            for code, resp in op.get("responses", {}).items():
                if "$ref" in resp:
                    rows.append(f"- `{code}`: [Error](schemas.md#error)")
                    continue
                b = body_schema(resp.get("content", {}))
                rows.append(f"- `{code}`: {cell(resp.get('description'))}" + (f", {b}" if b else ""))
            if rows:
                parts.append("Responses:\n\n" + "\n".join(rows) + "\n")
        write(f"api/{tag}.md", "\n".join(parts))
        index.append((tag, tag_desc.get(tag, ""), len(ops)))

    sparts = [banner(src), "# Schemas\n",
              "Request and response bodies of the Triton Cloud API, by name.\n"]
    for name in sorted(schemas, key=str.lower):
        s = schemas[name]
        sparts.append(f"## {name}\n")
        if s.get("description"):
            sparts.append(s["description"].strip() + "\n")
        props = s.get("properties")
        if props:
            required = set(s.get("required", []))
            sparts.append("| Field | Type | Required | Description |")
            sparts.append("|---|---|---|---|")
            for field, fs in props.items():
                sparts.append(
                    f"| `{field}` | {schema_type(fs)} | {'yes' if field in required else 'no'} "
                    f"| {cell(fs.get('description'))} |"
                )
            sparts.append("")
        elif any(k in s for k in ("oneOf", "anyOf", "allOf", "enum")) or s.get("type") not in (None, "object"):
            variants = s.get("oneOf") or s.get("anyOf")
            if variants:
                sparts.append("One of:\n")
                for v in variants:
                    desc = cell(v.get("description"))
                    sparts.append(f"- {schema_type(v) if '$ref' in v or 'enum' in v else render_inline(v)}"
                                  + (f": {desc}" if desc else ""))
                sparts.append("")
            else:
                sparts.append(f"Type: {schema_type(s)}\n")
    write("api/schemas.md", "\n".join(sparts))

    lines = [banner(src), f"# {info['title']}\n", info.get("description", "") + "\n",
             f"Version `{info['version']}`.\n",
             "| Tag | Operations | About |", "|---|---|---|"]
    for tag, desc, n in index:
        lines.append(f"| [{tag}]({tag}.md) | {n} | {cell(desc)} |")
    lines.append("\nBodies: [schemas.md](schemas.md).")
    write("api/README.md", "\n".join(lines))
    return index


def render_inline(schema: dict) -> str:
    props = schema.get("properties")
    if props:
        fields = ", ".join(f"`{k}`: {schema_type(v)}" for k, v in props.items())
        return "{ " + fields + " }"
    return schema_type(schema)


# ---------------------------------------------------------------------------
# Copied docs
# ---------------------------------------------------------------------------

def copy_docs(source: Path) -> None:
    for src_rel, out_rel in COPIED_DOCS:
        text = (source / src_rel).read_text()
        for old, new in LINK_REWRITES.items():
            text = text.replace(f"]({old}", f"]({new}")
        write(out_rel, banner(f"`{src_rel}`") + "\n" + text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tritonctl", required=True, help="path to the tritonctl binary")
    ap.add_argument("--source", required=True, type=Path, help="mariana-trench checkout")
    args = ap.parse_args()

    source = args.source.resolve()
    if not (source / SPEC).is_file():
        sys.exit(f"no Cloud API spec at {source / SPEC}")

    if OUT.exists():
        shutil.rmtree(OUT)
    version, cli_index = generate_cli(args.tritonctl)
    api_index = generate_api(source)
    copy_docs(source)
    write("SOURCE.md",
          f"# Sources\n\n- mariana-trench `{git_rev(source)}`\n- `{version}`\n")
    print(f"cli: {len(cli_index)} files, api: {len(api_index)} tags, docs: {len(COPIED_DOCS)}")


if __name__ == "__main__":
    main()
